import os
import sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from harness import Env
ok = fail = 0
def check(l, c, i=None):
    global ok, fail
    if c: ok += 1; print('  ok   ', l)
    else: fail += 1; print('  FEHLER', l, i)
def notes(env, src): return [d['text'] for s, n, d in env.events if s == src and n == 'core:notify']
def last(env, src): n = notes(env, src); return n[-1] if n else None
def ev(env, src, name): return env.events_for(src, name)

env = Env()
for s in (1, 2, 3, 4):
    env.connect(s, [f'license:{s}'])
    env.call(s, 'auth_register', {'email': f'{s}@t.de', 'password': 'passwort123'})
ids = {}
for s, (fn, ln) in zip((1, 2, 3, 4), [('Fabian', 'Nandes'), ('Lena', 'Wojcik'), ('Mira', 'Brandt'), ('Jonas', 'Lehmkuhl')]):
    ids[s] = env.call(s, 'char_create', {'firstname': fn, 'lastname': ln, 'dateOfBirth': '1995-01-01', 'gender': 'male'})['data']['characterId']
fab, lena, mira, jonas = ids[1], ids[2], ids[3], ids[4]
env.command(0, f'setrank {fab} chief'); env.command(0, f'setrank {lena} assistant')
for s in (1, 2, 3, 4): env.call(s, 'char_select', {'id': ids[s]})
env.command(1, 'aduty'); env.command(2, 'aduty')
env.positions[1] = [100.0, 100.0, 30.0]; env.positions[2] = [300.0, 100.0, 30.0]; env.positions[3] = [500.0, 500.0, 30.0]; env.positions[4] = [-50.0, 600.0, 20.0]

print('Spieler erstellt Ticket')
r = env.call(3, 'ticket_mine', {})
check('Leere Liste', r['ok'] and not r['data']['tickets'] and r['data']['cooldown'] == 0)
r = env.call(3, 'ticket_create', {'category': 'bug', 'text': 'Hi'})
check('Zu kurz', r['error'] == 'invalid_text')
r = env.call(3, 'ticket_create', {'category': 'quatsch', 'text': 'Ich hänge im Boden fest'})
check('Falsche Kategorie', r['error'] == 'invalid_category')
r = env.call(3, 'ticket_create', {'category': 'bug', 'text': '  Ich hänge am Würfelpark im Boden fest  '})
t1 = r['data']['ticket']['id']
check('Ticket erstellt', r['ok'] and r['data']['ticket']['status'] == 'open' and r['data']['cooldown'] == 25, r)
check('Team im Dienst bekommt Meldung mit /claim', f'/claim {t1}' in (last(env, 1) or '') and f'/claim {t1}' in (last(env, 2) or '') and 'Mira Brandt (ID 3)' in last(env, 1), last(env, 1))
check('Spieler ohne Recht bekommt keine Meldung', not any('Neues Ticket' in t for t in notes(env, 4)))
r = env.call(3, 'ticket_create', {'category': 'other', 'text': 'Noch eins bitte'})
check('Cooldown gilt auch fürs Erstellen', r['error'] == 'cooldown' and r['data']['cooldown'] > 0)
env.tick(26000)
r = env.call(3, 'ticket_create', {'category': 'other', 'text': 'Noch eins bitte'})
check('Nur ein offenes Ticket pro Charakter', r['error'] == 'already_open' and r['data']['id'] == t1)
r = env.call(3, 'ticket_get', {'id': t1})
check('Spieler sieht sein Ticket mit Name und ID', r['ok'] and r['data']['messages'][0]['authorName'] == 'Mira Brandt' and r['data']['messages'][0]['authorId'] == mira
      and r['data']['messages'][0]['body'] == 'Ich hänge am Würfelpark im Boden fest' and r['data']['canWrite'], r)
r = env.call(3, 'ticket_send', {'id': t1, 'text': 'Bin bei den Tennisplätzen'})
check('Spieler schreibt', r['ok'] and r['data']['cooldown'] == 25)
r = env.call(3, 'ticket_send', {'id': t1, 'text': 'Hallo?? Jemand da?'})
check('25 Sekunden Pause für Spieler', r['error'] == 'cooldown' and 20 <= r['data']['cooldown'] <= 25, r)
r = env.call(4, 'ticket_get', {'id': t1})
check('Fremder Spieler sieht das Ticket nicht', r['error'] == 'not_found')
env.call(3, 'ticket_ui_close', {})

print('Team')
r = env.call(4, 'ticket_list', {'filter': 'open'})
check('Spieler hat keine Team-Liste', r['error'] == 'no_permission')
r = env.call(2, 'ticket_list', {'filter': 'open'})
check('Assistant sieht offene Tickets', r['ok'] and r['data']['tickets'][0]['id'] == t1 and r['data']['counts']['open'] == 1 and r['data']['tickets'][0]['serverId'] == 3, r['data'])
check('Assistant darf nicht teleportieren oder beobachten', r['data']['permissions'] == {'teleport': False, 'spectate': False})
r = env.call(2, 'ticket_send', {'id': t1, 'text': 'Ich schaue mal'})
check('Ohne Übernehmen nicht schreiben', r['error'] == 'not_claimed')
env.command(2, f'claim {t1}')
check('/claim übernimmt', 'übernommen' in last(env, 2) and ev(env, 2, 'core:ticket:open')[-1]['id'] == t1, last(env, 2))
check('Spieler erfährt es', 'Lena Wojcik kümmert sich' in (last(env, 3) or ''), last(env, 3))
r = env.call(1, 'ticket_action', {'action': 'claim', 'id': t1})
check('Zweiter Admin kann nicht übernehmen', r['error'] == 'claimed_by_other' and r['data']['name'] == 'Lena Wojcik', r)
env.call(3, 'ticket_get', {'id': t1})  # Spieler hat das Ticket offen
r = env.call(2, 'ticket_send', {'id': t1, 'text': 'Ich komme gleich, bleib wo du bist'})
check('Admin schreibt ohne Pause', r['ok'] and r['data']['cooldown'] == 0)
r = env.call(2, 'ticket_send', {'id': t1, 'text': 'Noch eine Nachricht direkt hinterher'})
check('Admin schreibt gleich nochmal', r['ok'])
live = ev(env, 3, 'core:ticket:message')
check('Spieler bekommt die Antwort live', live and live[-1]['message']['authorName'] == 'Lena Wojcik' and live[-1]['message']['role'] == 'admin')
env.tick(26000)
env.events.clear()
r = env.call(3, 'ticket_send', {'id': t1, 'text': 'Danke, ich warte'})
check('Nur die Bearbeiterin bekommt die neue Nachricht gemeldet', any('Neue Nachricht in Ticket' in t for t in notes(env, 2)) and not any('Neue Nachricht' in t for t in notes(env, 1)), (notes(env, 1), notes(env, 2)))

print('Hingehen und Beobachten')
r = env.call(2, 'ticket_goto', {'id': t1})
check('Assistant darf nicht hingehen', r['error'] == 'no_permission')
r = env.call(1, 'ticket_goto', {'id': t1})
tp = ev(env, 1, 'core:admin:teleport')
check('Chief geht hin', r['ok'] and tp and abs(tp[-1]['x'] - 501.0) < 0.01)
r = env.call(1, 'ticket_spectate', {'id': t1})
sp = ev(env, 1, 'core:admin:spectate')
check('Chief beobachtet', r['ok'] and sp[-1]['on'] is True and sp[-1]['serverId'] == 3)
env.command(1, 'spec')
sp = ev(env, 1, 'core:admin:spectate')
check('/spec beendet und bringt zurück an den Startpunkt', sp[-1]['on'] is False and abs(sp[-1]['position']['x'] - 100.0) < 0.01, sp[-1])

print('/spec')
env.command(1, f'spec {jonas}')
check('/spec ID', ev(env, 1, 'core:admin:spectate')[-1]['serverId'] == 4)
env.command(1, f'spec {mira}')
sp = ev(env, 1, 'core:admin:spectate')
check('Wechsel zu anderem Spieler', sp[-1]['on'] and sp[-1]['serverId'] == 3)
env.command(1, f'tp {jonas}')
sp = ev(env, 1, 'core:admin:spectate')
check('/tp beendet Beobachten ohne Rückteleport', sp[-1]['on'] is False and sp[-1].get('position') is None, sp[-1])
env.command(1, 'dim 4')
env.command(1, f'spec {mira}')
check('Beim Beobachten in die Dimension des Spielers', env.lua.eval('BUCKETS[1]') == 0)
env.command(3, 'relog')
check('Spieler loggt aus: Beobachten endet, zurück in Dimension 4', ev(env, 1, 'core:admin:spectate')[-1]['on'] is False and env.lua.eval('BUCKETS[1]') == 4 and 'verlassen' in last(env, 1))
env.call(3, 'auth_login', {'email': '3@t.de', 'password': 'passwort123'}); env.call(3, 'char_select', {'id': mira})
env.command(1, 'dim 0')
env.command(2, f'spec {mira}')
check('Assistant hat kein /spec', 'keine Rechte' in last(env, 2))
env.command(1, f'spec {fab}')
check('Sich selbst nicht', 'selbst' in last(env, 1))

print('Schließen und wieder öffnen')
r = env.call(1, 'ticket_action', {'action': 'close', 'id': t1})
check('Anderer Admin kann fremdes Ticket nicht schließen', r['error'] == 'claimed_by_other')
r = env.call(2, 'ticket_action', {'action': 'close', 'id': t1})
check('Bearbeiterin schließt', r['ok'] and r['data']['ticket']['status'] == 'closed')
check('Spieler bekommt Bescheid', any('wurde geschlossen' in t for t in notes(env, 3)))
env.tick(26000)
r = env.call(3, 'ticket_send', {'id': t1, 'text': 'Noch eine Frage dazu'})
check('Spieler kann nicht mehr schreiben', r['error'] == 'closed')
r = env.call(3, 'ticket_get', {'id': t1})
check('Verlauf bleibt sichtbar, mit Systemnachrichten', r['ok'] and not r['data']['canWrite'] and any(m['role'] == 'system' and 'geschlossen' in m['body'] for m in r['data']['messages']))
r = env.call(3, 'ticket_create', {'category': 'question', 'text': 'Neue Frage zu Fraktionen'})
t2 = r['data']['ticket']['id']
check('Neues Ticket geht nach dem Schließen', r['ok'] and t2 != t1)
r = env.call(3, 'ticket_mine', {})
check('Liste: aktuelles zuerst, altes geschlossen darunter', [t['id'] for t in r['data']['tickets']] == [t2, t1], r['data']['tickets'])
r = env.call(1, 'ticket_action', {'action': 'reopen', 'id': t1})
check('Admin öffnet wieder und übernimmt', r['ok'] and r['data']['ticket']['status'] == 'claimed' and r['data']['ticket']['claimedById'] == fab)
env.tick(26000)
r = env.call(3, 'ticket_send', {'id': t1, 'text': 'Danke fürs Öffnen'})
check('Spieler kann wieder schreiben', r['ok'], r)
r = env.call(1, 'ticket_list', {'filter': 'mine'})
check('Filter "Meine"', [t['id'] for t in r['data']['tickets']] == [t1] and r['data']['counts'] == {'open': 1, 'claimed': 1, 'mine': 1}, r['data'])
r = env.call(1, 'ticket_list', {'filter': 'player', 'characterId': mira})
check('Alle Tickets eines Charakters', len(r['data']['tickets']) == 2)
r = env.call(1, 'ticket_action', {'action': 'unclaim', 'id': t1})
check('Freigeben', r['ok'] and r['data']['ticket']['status'] == 'open')
env.command(2, 'aduty')
r = env.call(2, 'ticket_action', {'action': 'claim', 'id': t2})
check('Ohne Dienst nicht übernehmen', r['error'] == 'duty_required')
env.command(2, 'aduty')
env.command(2, f'claim {t2}')
env.command(2, 'relog')
r = env.call(1, 'ticket_action', {'action': 'claim', 'id': t2})
check('Bearbeiterin offline: anderer Admin kann übernehmen', r['ok'], r)

r = env.call(1, 'ticket_get', {'id': t2})
check('Admin sieht fremdes Ticket, darf erst nach Übernehmen schreiben', r['ok'] and r['data']['canWrite'] is True)
print('Log und Befehlsliste')
env.flush_log()
acts = [x['action'] for x in env.sql("SELECT action FROM audit_log WHERE category='ticket'")]
check('Ticket-Aktionen im Log', all(a in acts for a in ('ticket_create', 'ticket_claim', 'ticket_close', 'ticket_reopen', 'ticket_unclaim', 'ticket_view')), set(acts))
acts = [x['action'] for x in env.sql("SELECT action FROM audit_log WHERE action LIKE 'spectate%%'")]
check('Beobachten im Log', 'spectate_start' in acts and 'spectate_stop' in acts)
r = env.call(1, 'admin_overview', {})
groups = r['data']['commands']
entries = [e for g in groups for e in g['entries']]
check('Befehlsliste im Admin-Menü', len(entries) > 40 and r['data']['ticketsOpen'] == 1, r['data'].get('ticketsOpen'))
spec = next(e for e in entries if e['usage'].startswith('/spec'))
check('Rang wird aus der Config berechnet', spec['rank'] == 'Junior Administrator', spec)
covered = env.to_py(env.lua.eval('AdminHelp.CoveredCommands()'))
names = env.to_py(env.lua.eval('Core.AdminCommandNames'))
missing = [n for n in names if n not in covered]
check('Jeder Admin-Befehl steht in der Liste', not missing, missing)
print(f'\n{ok} ok, {fail} Fehler')
