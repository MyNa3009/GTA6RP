ok = fail = 0
def check(l, c, i=None):
    global ok, fail
    if c: ok += 1; print('  ok   ', l)
    else: fail += 1; print('  FEHLER', l, i)
def notes(env, src): return [(d['text'], d['type'], d.get('title')) for s, n, d in env.events if s == src and n == 'core:notify']
def last(env, src): n = notes(env, src); return n[-1] if n else (None, None, None)
def ev(env, src, name): return env.events_for(src, name)
def clear(env): env.events.clear()

