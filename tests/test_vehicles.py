import os
import sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from harness import Env
ok=fail=0
def check(l,c,i=None):
    global ok,fail
    if c: ok+=1; print('  ok   ',l)
    else: fail+=1; print('  FEHLER',l,i)
env=Env()
for s in (1,2,3):
    env.connect(s,[f'license:{s}'],position=(1.0,1.0,70.0))
    env.call(s,'auth_register',{'email':f'{s}@t.de','password':'passwort123'})
    r=env.call(s,'char_create',{'firstname':'Test','lastname':'Nummer'+'abc'[s-1],'dateOfBirth':'1995-01-01','gender':'male'})
    env.call(s,'char_select',{'id':r['data']['characterId']})
env.command(0,'setrank 1 senior'); env.command(0,'setrank 2 serveradmin'); env.command(0,'setrank 3 junior')
r=env.call(1,'admin_vehicle_spawn',{'model':'adder'})
check('Spawn ohne Dienst abgelehnt', r['error']=='duty_required', r)
for s in (1,2,3): env.command(s,'aduty')
r=env.call(1,'admin_vehicle_spawn',{'model':'adder'})
check('Senior spawnt', r['ok'] and r['data']['plate']=='ADMIN', r)
r=env.call(2,'admin_vehicle_spawn',{'model':'zentorno'})
check('Server Admin (Stufe 4) spawnt', r['ok'], r)
r=env.call(3,'admin_vehicle_spawn',{'model':'adder'})
check('Junior darf nicht spawnen', r['error']=='no_permission', r)
r=env.call(1,'admin_vehicle_spawn',{'model':'adder; DROP'})
check('Unsinniges Modell abgelehnt', r['error']=='invalid_model', r)
r=env.call(2,'admin_vehicle_boost',{'percent':200})
check('Server Admin darf nicht boosten', r['error']=='no_permission', r)
r=env.call(1,'admin_vehicle_boost',{'percent':300,'model':'ADDER','plate':'ADMIN'})
check('Senior boostet 300 %', r['ok'] and r['data']['percent']==300, r)
r=env.call(1,'admin_vehicle_boost',{'percent':301})
check('Mehr als 300 % abgelehnt', r['error']=='invalid_percent', r)
env.lua.execute("VEHICLES[600] = { x = 2.0, y = 1.0, z = 70.0, plate = 'LS 4821' }; VEHICLES[601] = { x = 400.0, y = 400.0, z = 70.0, plate = 'FAR 1' }")
r=env.call(1,'admin_vehicle_delete',{'netId':600,'model':'ADDER'})
check('Fahrzeug gelöscht', r['ok'] and env.lua.eval('DELETED[1]')==600, r)
r=env.call(1,'admin_vehicle_delete',{'netId':77})
check('Kein Fahrzeug', r['error']=='no_vehicle', r)
r=env.call(1,'admin_vehicle_delete',{'netId':601})
check('Fahrzeug am anderen Ende der Karte abgelehnt', r['error']=='too_far' and env.lua.eval('DELETED[2]') is None, r)
env.command(3,'aduty')
check('Junior ist nicht mehr im Dienst', not env.lua.eval('Core.IsOnDuty(3)'))
env.lua.execute("VEHICLES[602] = { x = 1.0, y = 3.0, z = 70.0, plate = 'LS 1107' }")
r=env.call(3,'admin_vehicle_delete',{'netId':602})
check('Junior löscht ohne Admin-Dienst', r['ok'] and env.lua.eval('DELETED[2]')==602, r)
env.connect(4,['license:4'],position=(1.0,1.0,70.0))
env.call(4,'auth_register',{'email':'4@t.de','password':'passwort123'})
