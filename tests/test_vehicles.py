env.call(4,'char_select',{'id':r['data']['characterId']})
env.lua.execute("VEHICLES[603] = { x = 1.0, y = 1.0, z = 70.0 }")
r=env.call(4,'admin_vehicle_delete',{'netId':603})
check('Spieler darf nicht löschen', r['error']=='no_permission', r)
env.command(3,'aduty')
r=env.call(3,'admin_noclip',{'on':True})
check('Noclip ab Stufe 2', r['ok'], r)
env.flush_log()
rows=env.sql("SELECT action FROM audit_log WHERE action LIKE 'vehicle%%' ORDER BY id")
check('Fahrzeuge im Log', [x['action'] for x in rows]==['vehicle_spawn','vehicle_spawn','vehicle_boost','vehicle_delete','vehicle_delete'], rows)
row=env.sql("SELECT data FROM audit_log WHERE action='vehicle_delete' ORDER BY id LIMIT 1")[0]
check('Kennzeichen vom Server im Log', 'LS 4821' in row['data'], row)
